ENGINE = PolicyEngine()


@pytest.mark.parametrize(
    ("case_id", "lang", "code", "verdict", "rule"), CASES, ids=[c[0] for c in CASES]
)
def test_corpus_case(case_id, lang, code, verdict, rule):
    d = ENGINE.evaluate(
        ActionRequest(id=case_id, task_id="corpus", tool="run_code", lang=lang, code=code)
    )
    assert d.verdict == verdict, (case_id, d.verdict, d.rules_fired, d.reason)
    if rule:
        assert rule in d.rules_fired, (case_id, d.rules_fired)
    if verdict == "deny":
        assert d.rules_fired, case_id


def test_corpus_size():
    adv = [c for c in CASES if "adv" in c[0]]
    ben = [c for c in CASES if "ben" in c[0]]
    assert len([c for c in ben if c[0].startswith("sreben")]) >= 30
    assert all(c[3] == "deny" for c in adv)
    assert all(c[3] == "allow" for c in ben)
