"""Generate docs/CHECKS.md from the pytest collection.

Usage:
  python scripts/gen_checks.py          # rewrite docs/CHECKS.md
  python scripts/gen_checks.py --check  # exit 1 if docs/CHECKS.md is stale
"""

import sys
from collections import defaultdict
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "CHECKS.md"


class _Collector:
    def __init__(self):
        self.items = []

    def pytest_collection_finish(self, session):
        for item in session.items:
            doc = (getattr(item, "obj", None).__doc__ or "").strip().splitlines()
            self.items.append((item.nodeid, doc[0] if doc else ""))


def collect():
    col = _Collector()
    rc = pytest.main(
        ["--collect-only", "-qq", "-p", "no:cacheprovider", str(ROOT / "tests")], plugins=[col]
    )
    if rc != 0:
        raise SystemExit(f"pytest collection failed with exit code {rc}")
    return col.items


def render(items):
    by_file = defaultdict(list)
    for nodeid, doc in items:
        path, _, name = nodeid.partition("::")
        by_file[path].append((name, doc))
    lines = [
        "# Airlock Automated Checks",
        "",
        "Generated by `python scripts/gen_checks.py` from `pytest --collect-only`; do not edit by hand.",
        "CI fails if this file differs from the collection (`--check`).",
        "",
        "Pass/skip status depends on the environment and is not recorded here. Docker tests skip",
        "with an explicit reason when no daemon is reachable; gVisor tests skip unless runsc is present.",
        "",
        f"Total collected tests: **{len(items)}** in {len(by_file)} files.",
        "",
        "| File | Tests |",
        "|------|------:|",
    ]
    lines += [f"| `{f}` | {len(v)} |" for f, v in sorted(by_file.items())]
    for f, tests in sorted(by_file.items()):
        lines += ["", f"## `{f}`", "", "| Test | Description |", "|------|-------------|"]
        for name, doc in tests:
            safe = doc.replace("|", "\\|")
            nm = name.replace("|", "\\|").replace("\n", "\\n")
            lines.append(f"| `{nm}` | {safe} |")
    return "\n".join(lines) + "\n"


def main():
    text = render(collect())
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            print("docs/CHECKS.md is stale; run: python scripts/gen_checks.py", file=sys.stderr)
            return 1
        print("docs/CHECKS.md is up to date")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
