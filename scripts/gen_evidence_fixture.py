#!/usr/bin/env python3
"""Regenerate tests/fixtures/evidence_bundle deterministically (manual; not a test).

Writes sample-evidence-bundle.zip and auditor-trusted.pem using FakeRunner.
Does not run during pytest. Regenerate when the format changes:

  python scripts/gen_evidence_fixture.py
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from fastapi.testclient import TestClient  # noqa: E402

from airlock.schemas import Cleanup  # noqa: E402
from airlock.web.app import Settings, create_app  # noqa: E402
from airlock.web.chain import load_or_create_signer  # noqa: E402
from tests.test_web_api import FakeRunner  # noqa: E402

OUT = ROOT / "tests" / "fixtures" / "evidence_bundle"


def main() -> int:
    data = OUT / "_gen_data"
    if data.exists():
        import shutil

        shutil.rmtree(data)
    settings = Settings(data_dir=data)
    app = create_app(settings, runner_factory=FakeRunner, llm_factory=lambda: None)
    app.state.pipeline.verifier.verify_cleanup = lambda name: Cleanup(
        container_absent=True, network_absent=True, evidence="fake runner"
    )
    client = TestClient(app)
    r = client.post("/api/task", json={"kind": "injected", "mode": "replay_compromised"})
    r.raise_for_status()
    task_id = r.json()["task_id"]
    blob = (data / "evidence_bundles" / f"{task_id}.zip").read_bytes()
    signer = load_or_create_signer(data / "keys")
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "sample-evidence-bundle.zip").write_bytes(blob)
    (OUT / "auditor-trusted.pem").write_text(signer.export_public_key())
    (OUT / "README.md").write_text(
        "# Evidence Bundle v1 fixture\n\n"
        "Generated by `python scripts/gen_evidence_fixture.py` (not by pytest).\n\n"
        "```bash\n"
        "airlock verify-bundle tests/fixtures/evidence_bundle/sample-evidence-bundle.zip \\\n"
        "  --pubkey tests/fixtures/evidence_bundle/auditor-trusted.pem\n"
        "```\n\n"
        "Exit 0 = authentic + recount VERIFIED (replay_compromised — not live-model).\n"
        "Exit 1 = authentic + recount FAILED. Exit 2 = authentic incomplete/inconclusive.\n"
        "Exit 19 = unexpected/internal (fail-closed). "
        "The PEM is the out-of-band trust anchor for this fixture; "
        "bundled signing.pub is convenience only.\n"
    )
    print(f"wrote {OUT / 'sample-evidence-bundle.zip'} ({len(blob)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
